#include <iostream>  // Библиотека для ввода и вывода
#include <iomanip>   // Библиотека для оформления таблицы

using namespace std;

int main() {

    // Объявляем переменные:
    // a - начало интервала
    // b - конец интервала
    // h - шаг изменения x
    double a, b, h;

    // Просим пользователя ввести начало, конец интервала и шаг
    cout << "Enter a, b and h: ";
    cin >> a >> b >> h;

    // Проверяем правильность введённых данных
    // Начало интервала не должно быть больше конца
    // Шаг должен быть положительным
    if (a > b || h <= 0) {
        cout << "Error: Invalid interval or step." << endl;
        return 1;
    }

    // Выводим название функции
    cout << "\nFunction: y = -x^2 + 4x\n";

    // Выводим заголовки столбцов таблицы
    cout << left
         << setw(15) << "X"
         << setw(15) << "Y"
         << endl;

    // Выводим разделительную линию
    cout << "------------------------------" << endl;

    // Цикл перебирает значения x от a до b
    // После каждого повторения x увеличивается на h
    for (double x = a; x <= b; x += h) {

        // Вычисляем значение функции
        // y = -x^2 + 4x
        double y = -x * x + 4 * x;

        // Выводим текущее значение x и результат y
        // fixed - обычный десятичный формат
        // setprecision(4) - четыре знака после запятой
        // setw(15) - ширина столбца 15 символов
        cout << fixed << setprecision(4)
             << left
             << setw(15) << x
             << setw(15) << y
             << endl;
    }

    // Сообщаем об успешном завершении программы
    cout << "\nCalculation completed successfully!" << endl;

    return 0; // Завершаем программу
}
