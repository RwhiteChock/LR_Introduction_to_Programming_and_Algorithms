#include <iostream>

int main()
{
    // Переменная hours хранит количество часов,
    // которое пользователь вводит с клавиатуры.
    // Используем тип int, так как часы в нашей задаче являются целым числом.
    int hours;

    // Переменная minutes будет хранить результат перевода часов в минуты.
    int minutes;

    // Выводим пользователю приглашение для ввода данных.
    // Текст в консоли написан на английском языке.
    std::cout << "Enter the number of hours: ";

    // Считываем количество часов с клавиатуры.
    std::cin >> hours;

    // В одном часе содержится 60 минут.
    // Поэтому умножаем количество часов на 60.
    minutes = hours * 60;

    // Выводим полученное количество минут.
    std::cout << "Number of minutes: " << minutes << std::endl;

    // Завершаем работу программы.
    return 0;
}