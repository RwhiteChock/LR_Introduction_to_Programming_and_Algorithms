#include <iostream>
#include <iomanip>
#include <cmath>
#include <limits>

int main()
{
    // =========================================
    // 1. ВВОД ИСХОДНЫХ ДАННЫХ
    // =========================================

    // x — основание степени.
    // Используем double, поскольку основание может быть дробным.
    double x;

    // y — показатель степени.
    // По условию задания он должен быть положительным целым числом.
    // Поэтому используем тип int.
    int y;

    // Запрашиваем у пользователя значение основания.
    std::cout << "Enter the base x: ";

    // Считываем значение x.
    std::cin >> x;

    // Проверяем наличие ошибки ввода.
    // std::cin.fail() возвращает true, если введено значение
    // неподходящего типа, например текст вместо числа.
    while (std::cin.fail())
    {
        // Очищаем состояние ошибки потока.
        std::cin.clear();

        // Удаляем неправильные данные из входного буфера.
        std::cin.ignore(
            std::numeric_limits<std::streamsize>::max(),
            '\n'
        );

        // Выводим понятное сообщение об ошибке.
        std::cout << "Invalid input. Enter a number for x: ";

        // Повторно считываем x.
        std::cin >> x;
    }

    // Запрашиваем показатель степени.
    std::cout << "Enter a positive integer exponent y: ";

    // Считываем значение y.
    std::cin >> y;

    // Проверяем два условия:
    // 1. не должно быть ошибки ввода;
    // 2. показатель степени должен быть больше нуля.
    while (std::cin.fail() || y <= 0)
    {
        // Очищаем состояние ошибки входного потока.
        std::cin.clear();

        // Удаляем неправильные данные из буфера.
        std::cin.ignore(
            std::numeric_limits<std::streamsize>::max(),
            '\n'
        );

        // Сообщаем пользователю, какое значение требуется.
        std::cout << "Invalid input. y must be a positive integer: ";

        // Повторно считываем y.
        std::cin >> y;
    }

    // =========================================
    // 2. ВЫЧИСЛЕНИЕ С ПОМОЩЬЮ std::pow
    // =========================================

    // Функция std::pow используется для возведения числа
    // в заданную степень.
    //
    // Второй аргумент функции std::pow имеет вещественный тип.
    // Поэтому здесь специально демонстрируем явное приведение
    // показателя степени y из int в double
    // с помощью static_cast<double>.
    double resultPow =
        std::pow(x, static_cast<double>(y));

    // =========================================
    // 3. ВЫЧИСЛЕНИЕ С ПОМОЩЬЮ ЦИКЛА
    // =========================================

    // Начинаем с 1.0, потому что умножение любого числа
    // на единицу не изменяет его значение.
    double resultLoop = 1.0;

    // Цикл выполняется y раз.
    // На каждом шаге результат умножается на основание x.
    //
    // Например, если x = 2 и y = 3:
    // 1 * 2 = 2
    // 2 * 2 = 4
    // 4 * 2 = 8
    //
    // В результате получаем 2^3 = 8.
    for (int i = 0; i < y; ++i)
    {
        resultLoop *= x;
    }

    // =========================================
    // 4. СРАВНЕНИЕ ДВУХ РЕЗУЛЬТАТОВ
    // =========================================

    // Устанавливаем вывод десяти знаков после запятой,
    // чтобы можно было лучше увидеть возможную разницу
    // между двумя способами вычисления.
    std::cout << std::fixed << std::setprecision(10);

    std::cout << "\nResult using std::pow: "
        << resultPow << std::endl;

    std::cout << "Result using loop:     "
        << resultLoop << std::endl;

    // Вычисляем абсолютную разницу между результатами.
    double difference =
        std::abs(resultPow - resultLoop);

    std::cout << "Difference:             "
        << difference << std::endl;

    // =========================================
    // 5. СРАВНЕНИЕ float И double
    // =========================================

    // Создаём переменную типа float.
    // float имеет меньшую точность по сравнению с double.
    float floatValue = 0.0f;

    // Создаём переменную типа double.
    // double позволяет хранить вещественные значения
    // с большей точностью.
    double doubleValue = 0.0;

    // Выполняем 1000 сложений числа 0.1.
    // Это позволяет продемонстрировать накопление
    // погрешности при работе с вещественными числами.
    for (int i = 0; i < 1000; ++i)
    {
        // Литерал 0.1f имеет тип float.
        floatValue += 0.1f;

        // Литерал 0.1 имеет тип double.
        doubleValue += 0.1;
    }

    // Выводим результаты сравнения.
    std::cout << "\n=== Float vs Double ===\n";

    std::cout << "float after 1000 additions:  "
        << floatValue << std::endl;

    std::cout << "double after 1000 additions: "
        << doubleValue << std::endl;

    // Теоретически:
    // 1000 * 0.1 = 100.0
    std::cout << "Expected value:              "
        << 100.0 << std::endl;

    // =========================================
    // 6. УСЕЧЕНИЕ И ОКРУГЛЕНИЕ
    // =========================================

    // Создаём число с дробной частью.
    double testNumber = 7.8;

    // static_cast<int> преобразует double в int.
    // При таком преобразовании дробная часть отбрасывается.
    // Поэтому 7.8 превращается в 7.
    int truncatedValue =
        static_cast<int>(testNumber);

    // std::round округляет число до ближайшего целого.
    // Поэтому 7.8 превращается в 8.
    //
    // После округления результат явно приводится
    // к типу int.
    int roundedValue =
        static_cast<int>(std::round(testNumber));

    // Дополнительно показываем другой способ
    // неявного преобразования double в int.
    // В этом случае преобразование выполняется автоматически
    // при присваивании значения переменной типа int.
    int implicitValue = testNumber;

    // Выводим результаты сравнения.
    std::cout << "\n=== Truncation vs Rounding ===\n";

    std::cout << "Original number:       "
        << testNumber << std::endl;

    std::cout << "static_cast<int>:      "
        << truncatedValue << std::endl;

    std::cout << "Implicit conversion:   "
        << implicitValue << std::endl;

    std::cout << "std::round + cast:     "
        << roundedValue << std::endl;

    // Завершаем работу программы.
    return 0;
} 