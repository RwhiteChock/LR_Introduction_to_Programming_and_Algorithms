#include <iostream> // Подключаем библиотеку для ввода и вывода данных
using namespace std; // Позволяет использовать cout и cin без std::

int main() {
    // Объявляем три переменные для хранения введённых чисел
    double a, b, c;

    // Просим пользователя ввести три числа
    cout << "Enter three numbers: ";
    cin >> a >> b >> c;

    // Проверяем, правильно ли введены данные
    // Если вместо числа введены буквы или произошла ошибка,
    // выводим сообщение и завершаем программу
    if (cin.fail()) {
        cout << "Error: Invalid input!" << endl;
        return 1;
    }

    // Вычисляем сумму трёх введённых чисел
    double sum = a + b + c;

    // Проверяем, превышает ли сумма значение 100
    if (sum > 100) {
        // Если сумма больше 100, выводим соответствующее сообщение
        cout << "Big sum" << endl;
    }
    else {
        // Если сумма не больше 100, выводим её значение
        cout << "Sum = " << sum << endl;
    }

    // Завершаем программу без ошибок
    return 0;
}