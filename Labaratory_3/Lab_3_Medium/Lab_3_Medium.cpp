#include <iostream> // Подключаем библиотеку для ввода и вывода данных
#include <cmath>   // Подключаем библиотеку для математических функций
using namespace std; // Позволяет использовать cout и cin без std::

int main() {
    // Объявляем переменную для хранения введённого числа
    double number;

    // Просим пользователя ввести число
    cout << "Enter a number: ";
    cin >> number;

    // Проверяем корректность ввода
    // Если введены некорректные данные, сообщаем об ошибке
    // и завершаем программу с кодом 1
    if (cin.fail()) {
        cout << "Error: Invalid input!" << endl;
        return 1;
    }

    // Проверяем, является ли введённое число положительным
    if (number > 0) {
        // Если число положительное, вычисляем его квадратный корень
        // Функция sqrt() находится в библиотеке cmath
        cout << "Square root = " << sqrt(number) << endl;
    }
    else {
        // Если число равно нулю или отрицательное,
        // возводим его в квадрат умножением числа на само себя
        cout << "Square = " << number * number << endl;
    }

    // Завершаем программу без ошибок
    return 0;
}